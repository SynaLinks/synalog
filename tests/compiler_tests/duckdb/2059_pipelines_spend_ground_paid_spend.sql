  t_0_Order.id AS id,
  t_0_Order.who AS who,
  t_0_Order.item AS item,
  t_0_Order.n AS n
FROM
  t_1_Order AS t_0_Order
WHERE
  (t_0_Order.state = 'paid');

-- Interacting with table logica_home.Paid

DROP TABLE IF EXISTS logica_home.Spend;
CREATE TABLE logica_home.Spend AS WITH t_0_Price AS (SELECT * FROM (
  
    SELECT
      'tea' AS item,
      4 AS p
   UNION ALL
  
    SELECT
      'cake' AS item,
      9 AS p
   UNION ALL
  
    SELECT
      'coffee' AS item,
      6 AS p
  
) AS UNUSED_TABLE_NAME  )
SELECT
  Paid.who AS who,
  SUM(((Paid.n) * (Price.p))) AS total
FROM
  logica_home.Paid AS Paid, t_0_Price AS Price
WHERE
  (Price.item = Paid.item)
GROUP BY Paid.who;

-- Interacting with table logica_home.Spend

SELECT
  Spend.who AS who,
  Spend.total AS total
FROM
  logica_home.Spend AS Spend ORDER BY who, total;
