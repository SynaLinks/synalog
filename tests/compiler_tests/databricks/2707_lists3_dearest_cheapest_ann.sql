WITH t_2_I AS (SELECT * FROM VALUES
  (1, "ann", "pen", 2.5E0, 3, 1),
  (1, "ann", "ink", 7.0E0, 1, 2),
  (2, "ann", "pad", 4.0E0, 2, 1),
  (3, "bob", "pen", 2.5E0, 10, 1),
  (3, "bob", "cap", 1.25E0, 4, 2),
  (3, "bob", "ink", 7.0E0, 2, 3),
  (4, "cid", "pad", 4.0E0, 1, 1),
  (5, "cid", "pen", 2.5E0, 1, 1),
  (5, "cid", "pen", 2.5E0, 2, 2)
AS UNUSED_TABLE_NAME(`order`, customer, item, price, qty, pos))
SELECT
  SORT_ARRAY(COLLECT_LIST(STRUCT(I.price AS value, I.item AS arg)), false)[0].arg AS dear,
  SORT_ARRAY(COLLECT_LIST(STRUCT(I.price AS value, I.item AS arg)))[0].arg AS cheap
FROM
  t_2_I AS I
WHERE
  (I.customer = "ann");