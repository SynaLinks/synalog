  V.id AS id,
  ((((MOD(CAST(ROUND(SUBSTR(V.d, 1, 4)) AS BIGINT), NULLIF(4, 0))) = 0) AND ((MOD(CAST(ROUND(SUBSTR(V.d, 1, 4)) AS BIGINT), NULLIF(100, 0))) != 0)) OR ((MOD(CAST(ROUND(SUBSTR(V.d, 1, 4)) AS BIGINT), NULLIF(400, 0))) = 0)) AS leap
