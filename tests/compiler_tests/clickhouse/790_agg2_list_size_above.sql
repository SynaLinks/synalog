WITH t_2_V AS (SELECT * FROM (
  
    SELECT
      'a' AS n,
      3 AS s
   UNION ALL
  
    SELECT
      'b' AS n,
      9 AS s
   UNION ALL
  
    SELECT
      'c' AS n,
      1 AS s
   UNION ALL
  
    SELECT
      'd' AS n,
      5 AS s
  
) AS UNUSED_TABLE_NAME  ),
t_1_L AS (SELECT
  arrayMap(t -> t.1, groupArray(tuple(V.s))) AS l
FROM
  t_2_V AS V
WHERE
  (V.s > 2))
SELECT
  length(t_0_L.l) AS n
FROM
  t_1_L AS t_0_L;