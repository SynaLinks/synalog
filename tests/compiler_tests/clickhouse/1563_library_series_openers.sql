WITH t_0_Sequel AS (SELECT * FROM (
  
    SELECT
      2 AS book,
      3 AS next
   UNION ALL
  
    SELECT
      4 AS book,
      5 AS next
   UNION ALL
  
    SELECT
      8 AS book,
      9 AS next
   UNION ALL
  
    SELECT
      1 AS book,
      2 AS next
  
) AS UNUSED_TABLE_NAME  ),
t_1_IsSequel AS (SELECT
  t_2_Sequel.next AS book
FROM
  t_0_Sequel AS t_2_Sequel
GROUP BY 1)
SELECT
  Sequel.book AS book
FROM
  t_0_Sequel AS Sequel
WHERE
  NOT (Sequel.book IS NOT NULL AND CAST(Sequel.book AS Nullable(String)) IN (SELECT CAST(synalog_k0 AS Nullable(String)) FROM (SELECT
    IsSequel.book AS synalog_k0
  FROM
    t_1_IsSequel AS IsSequel
  GROUP BY 1) AS synalog_m))
GROUP BY 1 ORDER BY book;