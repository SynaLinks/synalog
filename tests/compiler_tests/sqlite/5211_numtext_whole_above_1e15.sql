WITH t_0_V AS (SELECT * FROM (
  
    SELECT
      0 AS k,
      (CAST(4999999999999999 AS REAL) * 2) AS x
   UNION ALL
  
    SELECT
      1 AS k,
      (CAST(91552734375 AS REAL) * 16384) AS x
   UNION ALL
  
    SELECT
      2 AS k,
      CAST(4503599627370497 AS REAL) AS x
   UNION ALL
  
    SELECT
      3 AS k,
      (-CAST(9007199254740991 AS REAL)) AS x
  
) AS UNUSED_TABLE_NAME  )
SELECT
  V.k AS k,
  SYNALOG_NUMBER_TEXT(V.x) AS t
FROM
  t_0_V AS V ORDER BY k NULLS LAST;